// Embeds assets/models/*.glb as base64 in js/model-data.js so the game loads without a web server.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'models');
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.glb')).sort()) out[f.replace('.glb', '')] = fs.readFileSync(path.join(dir, f)).toString('base64');
fs.writeFileSync(path.join(__dirname, '..', 'js', 'model-data.js'), '/* generated by tools/pack-models.js — do not edit */\nconst MODEL_DATA = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log(Object.keys(out).join(', '));
